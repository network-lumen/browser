// Creates the throwaway wallet the chain e2e tests spend from.
//
//   npm run e2e:wallet            once, then fund the address it prints
//   npm run e2e:wallet -- --force replace the existing one
//
// Writes tests/e2e/.env, which is gitignored. The address is printed; the
// mnemonic is not, so it does not end up in a terminal log or a screenshot.
import {
  Bip39,
  EnglishMnemonic,
  Random,
  Secp256k1,
  Slip10,
  Slip10Curve,
  Slip10RawIndex,
  ripemd160,
  sha256
} from '@cosmjs/crypto';
import bech32pkg from 'bech32';
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

// Depending on the resolved copy, encode/toWords sit at the top level or under
// a `bech32` key.
const bech32 = bech32pkg.bech32 ?? bech32pkg;

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(repoRoot, 'tests', 'e2e', '.env');

/** The path and encoding electron/ipc/wallet.cjs uses, so the app agrees. */
const DERIVATION = [
  Slip10RawIndex.hardened(44),
  Slip10RawIndex.hardened(118),
  Slip10RawIndex.hardened(0),
  Slip10RawIndex.normal(0),
  Slip10RawIndex.normal(0)
];

async function addressFor(mnemonic) {
  const seed = await Bip39.mnemonicToSeed(new EnglishMnemonic(mnemonic));
  const { privkey } = Slip10.derivePath(Slip10Curve.Secp256k1, seed, DERIVATION);
  const { pubkey } = await Secp256k1.makeKeypair(privkey);
  const hash = ripemd160(sha256(Secp256k1.compressPubkey(pubkey)));
  return bech32.encode('lmn', bech32.toWords(hash));
}

if (existsSync(target) && !process.argv.includes('--force')) {
  console.log(`${target} already exists. Pass --force to replace it.`);
  process.exit(0);
}

const mnemonic = Bip39.encode(Random.getBytes(16)).toString();
const address = await addressFor(mnemonic);

writeFileSync(
  target,
  [
    '# Generated by npm run e2e:wallet. Gitignored, and rightly so.',
    '# A throwaway wallet for the chain tests: never hold anything here that',
    '# matters, and never paste this mnemonic anywhere else.',
    `LUMEN_E2E_MNEMONIC="${mnemonic}"`,
    `LUMEN_E2E_ADDRESS=${address}`,
    '',
    '# Hard ceiling per transaction, in LMN. Signing refuses above it.',
    'LUMEN_E2E_MAX_LMN=0.05',
    ''
  ].join('\n'),
  'utf8'
);

console.log(`wrote ${target}`);
console.log(`fund this address: ${address}`);
